#!/usr/bin/env python3
"""Generate src/dsp/include/alfa/dsp/TierLimitsGenerated.h from the tier spec.

The tier spec (docs/tiers/allocation.json -> tier_budget.py -> allocation_by_tier.json) owns every
per-tier count; the DSP only mirrors it. Run after the tier file changes:

    python3 src/dsp/tools/gen_tier_limits.py          # rewrite the header
    python3 src/dsp/tools/gen_tier_limits.py --check  # exit 1 if the header is stale (CTest)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = pathlib.Path(__import__("os").environ.get("ALFA_TIER_SPEC", ROOT / "docs" / "tiers" / "allocation_by_tier.json"))
HEADER = ROOT / "src" / "dsp" / "include" / "alfa" / "dsp" / "TierLimitsGenerated.h"
TIERS = ["Lite", "Standard", "Pro", "Studio"]
# TierLimits field order, and the layout ceiling each must stay under (ControlFrame.h).
FIELDS = [
    ("partials", 64), ("fm_operators", 8), ("grain_layers", 8), ("polyphony", 64),
    ("voice_slots", 4), ("instance_slots", 4), ("mod_routes", 8), ("resonator_modes", 32),
    ("osc_unison", 8),
]
# DSP family (Family.h order, Off first) -> capacity families in allocation.json family_modules.
# A family listed under several takes the largest share (the guard protects it the most).
FAMILY_CAPACITY = [
    [], ["filter_resonator"], ["filter_resonator"], ["filter_resonator"],
    ["filter_resonator", "physical_modal"], ["nonlinear"], ["physical_modal"], ["delay_diffusion"],
    ["delay_diffusion"], ["physical_modal"], ["delay_diffusion"], ["delay_diffusion"],
    ["convolution_spatial"], ["spectral"], ["pitch_time"], ["convolution_spatial"],
]


def render() -> str:
    spec = json.loads(SOURCE.read_text())
    rows = []
    for tier in TIERS:
        limits = spec[tier]["dsp_limits"]
        values = []
        for key, ceiling in FIELDS:
            v = int(limits[key])
            if not 1 <= v <= ceiling:
                sys.exit(f"{tier}.dsp_limits.{key} = {v} is outside 1..{ceiling} (ControlFrame.h)")
            values.append(str(v))
        rows.append(f"    {{{', '.join(values)}}}, // {tier}")
    guards = []
    for tier in TIERS:
        guard = spec[tier]["audio_budget_guard"]
        share = float(guard["max_block_share"])
        if guard.get("budget_basis") != "per_second" or not 0.0 < share <= 1.0:
            sys.exit(f"{tier}.audio_budget_guard: need budget_basis per_second and 0 < max_block_share <= 1")
        pct = spec[tier]["family_share_pct"]
        weights = [max((float(pct[c]) for c in caps), default=0.0) for caps in FAMILY_CAPACITY]
        guards.append(f"    {{{share!r}f, {{{', '.join(f'{w!r}f' for w in weights)}}}}}, // {tier}")
    fields = ", ".join(k for k, _ in FIELDS)
    return (
        "// Generated by src/dsp/tools/gen_tier_limits.py from docs/tiers/allocation_by_tier.json.\n"
        "// Do not edit: change the tier spec and re-run the script.\n"
        "// Included by ControlFrame.h after TierLimits is defined.\n"
        "#pragma once\n\n// clang-format off\n"
        "namespace alfa::dsp::generated\n{\n\n"
        f"// {fields}\n"
        "inline constexpr TierLimits kTierLimits[4] = {\n"
        + "\n".join(rows)
        + "\n};\n\n"
        "// Audio budget guard: max share of real time, then each Family's capacity share (percent;\n"
        "// the guard degrades the lowest first among equally heavy slots).\n"
        "inline constexpr BudgetGuardSpec kBudgetGuard[4] = {\n"
        + "\n".join(guards)
        + "\n};\n\n} // namespace alfa::dsp::generated\n// clang-format on\n"
    )


def main() -> int:
    if not SOURCE.exists():
        print(f"{SOURCE} not found; skipping")
        return 77  # CTest SKIP_RETURN_CODE
    text = render()
    if "--check" in sys.argv:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is stale; run {pathlib.Path(__file__).relative_to(ROOT)}")
            return 1
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
